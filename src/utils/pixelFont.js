export const FONT_HEIGHT = 5;
export const LINE_HEIGHT = 8;

function glyph(ch) {
  return G[ch] || G[ch.toUpperCase()] || G['?'];
}

// True when the font has a glyph for ch (otherwise it renders as '?').
export function hasGlyph(ch) {
  return !!(G[ch] || G[ch.toUpperCase()]);
}

export function measureLine(text) {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1);
}

export function measure(text) {
  const lines = String(text).split('\n');
  return {
    width: Math.max(1, ...lines.map(measureLine)),
    height: lines.length * LINE_HEIGHT - (LINE_HEIGHT - FONT_HEIGHT),
    lines,
  };
}

// Draws text into a 2D context at integer coordinates.
export function drawText(ctx, text, x, y, color, align = 'left', width = 0) {
  const { lines } = measure(text);
  ctx.fillStyle = color;
  lines.forEach((line, li) => {
    const lw = measureLine(line);
    let cx = x;
    if (align === 'center') cx = x + Math.floor((width - lw) / 2);
    else if (align === 'right') cx = x + width - lw;
    const cy = y + li * LINE_HEIGHT;
    for (const ch of line) {
      const g = glyph(ch);
      for (let r = 0; r < g.length; r++) {
        for (let c = 0; c < g[r].length; c++) {
          if (g[r][c] === '#') ctx.fillRect(cx + c, cy + r, 1, 1);
        }
      }
      cx += g[0].length + 1;
    }
  });
}
